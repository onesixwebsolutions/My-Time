-- One override per user per date (was: one per date for the whole database).
DROP INDEX ux_day_overrides_date;
CREATE UNIQUE INDEX ux_day_overrides_user_date ON day_overrides (user_id, date);

-- ux_checklist_completions_item_date stays as is: an item belongs to exactly one user, so
