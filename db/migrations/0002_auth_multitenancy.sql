-- ---------------------------------------------------------------------------
-- ASP.NET Core Data Protection key ring (auth cookies / tokens survive restarts and are shared by
-- every App Service instance).
-- ---------------------------------------------------------------------------
CREATE TABLE data_protection_keys (
    id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    friendly_name  text NULL,
    xml            text NULL
);

-- ---------------------------------------------------------------------------
-- Tenant column on every user-owned table. Nullable only so pre-existing rows survive until the
-- first account claims them; the application always stamps it on insert.
-- ---------------------------------------------------------------------------
ALTER TABLE checklists            ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE checklist_items       ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE checklist_completions ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE timetable_templates   ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE timetable_blocks      ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE timetable_assignments ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE day_overrides         ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE future_tasks          ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE reminders             ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE notification_log      ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE app_settings          ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE simple_tasks          ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE constant_expenses     ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE varying_expenses      ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE completed_spends      ADD COLUMN user_id uuid NULL REFERENCES users (id) ON DELETE CASCADE;

