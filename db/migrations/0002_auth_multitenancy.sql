-- DayGrid migration 0002 — accounts (ASP.NET Core Identity), Data Protection key ring and
-- per-user data isolation.
--
-- Runs inside one transaction (SchemaMigrator). No CREATE EXTENSION — valid on Azure Database
-- for PostgreSQL Flexible Server. Safe on a database that already holds data: every existing
-- row keeps user_id NULL ("legacy") until the first account registers, at which point the app
-- assigns all legacy rows to that account in the same transaction that creates it.

-- ---------------------------------------------------------------------------
-- Identity: users, roles and their satellite tables (snake_case names; mapped in
-- Infrastructure/Data/Configurations/IdentityConfigurations.cs).
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id                      uuid PRIMARY KEY,
    user_name               varchar(256) NULL,
    normalized_user_name    varchar(256) NULL,
    email                   varchar(256) NULL,
    normalized_email        varchar(256) NULL,
    email_confirmed         bool NOT NULL DEFAULT false,
    password_hash           text NULL,
    security_stamp          text NULL,
    concurrency_stamp       text NULL,
    phone_number            text NULL,
    phone_number_confirmed  bool NOT NULL DEFAULT false,
    two_factor_enabled      bool NOT NULL DEFAULT false,
    lockout_end             timestamptz NULL,
    lockout_enabled         bool NOT NULL DEFAULT true,
    access_failed_count     int NOT NULL DEFAULT 0,
    display_name            varchar(100) NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now(),
    last_login_at           timestamptz NULL
);

-- The email is the user name; both are unique (case-insensitively, via the normalized columns).
CREATE UNIQUE INDEX ux_users_normalized_user_name ON users (normalized_user_name);
CREATE UNIQUE INDEX ux_users_normalized_email ON users (normalized_email);

CREATE TABLE roles (
    id                 uuid PRIMARY KEY,
    name               varchar(256) NULL,
    normalized_name    varchar(256) NULL,
    concurrency_stamp  text NULL
);

CREATE UNIQUE INDEX ux_roles_normalized_name ON roles (normalized_name);

CREATE TABLE user_roles (
    user_id  uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id  uuid NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, role_id)
);

CREATE INDEX ix_user_roles_role_id ON user_roles (role_id);

CREATE TABLE user_claims (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    claim_type   text NULL,
    claim_value  text NULL
);

CREATE INDEX ix_user_claims_user_id ON user_claims (user_id);

CREATE TABLE user_logins (
    login_provider         varchar(128) NOT NULL,
    provider_key           varchar(128) NOT NULL,
    provider_display_name  text NULL,
    user_id                uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    PRIMARY KEY (login_provider, provider_key)
);

CREATE INDEX ix_user_logins_user_id ON user_logins (user_id);

CREATE TABLE user_tokens (
    user_id         uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    login_provider  varchar(128) NOT NULL,
    name            varchar(128) NOT NULL,
    value           text NULL,
    PRIMARY KEY (user_id, login_provider, name)
);

CREATE TABLE role_claims (
    id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id      uuid NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
    claim_type   text NULL,
    claim_value  text NULL
);

CREATE INDEX ix_role_claims_role_id ON role_claims (role_id);

